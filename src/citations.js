const LIST = '(?:(?:, | and )\\d+)*';
export const CITATION_PATTERNS = [
    /\bArticles? \d+(?:\(\d+\))?(?:\([a-z]\))?/g,
    new RegExp(`\\bRecitals? \\d+${LIST}`, 'g'),
    /\bartikkel \d+(?: nr\. \d+)?(?: bokstav [a-f])?/g,
    new RegExp(`§§? ?\\d+${LIST}`, 'g'),
    /\bC-\d+\/\d+/g,
    new RegExp(`\\bparagraphs? \\d+${LIST}`, 'g'),
    new RegExp(`\\bExamples? \\d+${LIST}`, 'g'),
    /\bsection \d+/g,
];
export function findCitations(text) {
    const out = [];
    for (const re of CITATION_PATTERNS) {
        for (const m of String(text).matchAll(re)) {
            const t = m[0].replace(/^Articles/, 'Article').replace(/^Recitals/, 'Recital').replace(/^paragraphs/, 'paragraph')
                .replace(/^Examples/, 'Example').replace(/^§§ ?/, '§ ').replace(/^§(\d)/, '§ $1');
            const lead = /^(Recital|paragraph|Example|§) /.exec(t);
            if (lead)
                for (const n of t.slice(lead[0].length).split(/, | and /))
                    out.push(`${lead[1]} ${n}`);
            else
                out.push(t);
        }
    }
    return out;
}
export function unknownCitations(text) {
    return findCitations(text).filter((c) => !CITATIONS.has(c));
}
